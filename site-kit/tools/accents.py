#!/usr/bin/env python3
"""The product accents of the Lock Family (site-kit/COLOUR.md).

    python3 site-kit/tools/accents.py           # rewrite the block in assets/tokens.css
    python3 site-kit/tools/accents.py --check   # fail if the block is stale
    python3 site-kit/tools/accents.py --table   # the Markdown table of COLOUR.md

One base hue per product. Everything else (the text-safe ink, the pale
tint, the hero's coloured stock, the dark scheme) is derived here and
checked against WCAG AA before it is written, so a new accent cannot ship
an unreadable pair. Standard library only.
"""

import colorsys
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TOKENS = os.path.join(ROOT, 'assets', 'tokens.css')
BEGIN = '/* accents:begin (generated by site-kit/tools/accents.py, do not edit by hand) */'
END = '/* accents:end */'

# name: (base, degrees the hero's wash turns towards)
ACCENTS = {
    'lockfamily': ('#2346d2', 28),   # cobalt: the signature's ink
    'locksql': ('#6d35d8', 30),      # violet
    'lockmq': ('#c9400a', 22),       # orange
    'lockfile': ('#c21f6a', -24),    # pink
    'lockhttp': ('#0672a3', -26),    # sky
    'locklog': ('#1c7c3c', -34),     # green
    'lockssh': ('#5d7500', 30),      # olive
    'lea': ('#9a2bb3', 30),          # orchid
    'lockhub': ('#0b7a70', 28),      # teal: the mask's ink
    'lockkit': ('#9a5f00', -22),     # brass
}

# The neutrals the accents sit on (assets/tokens.css; tests keep them in step).
NEUTRAL = {
    'light': {'paper': '#fbf7ee', 'paper-2': '#f3ecdd', 'card': '#fffcf5', 'ink': '#1d1b17', 'ink-2': '#575146'},
    'dark': {'paper': '#1f1d26', 'paper-2': '#282531', 'card': '#2f2c3a', 'ink': '#ede6d6', 'ink-2': '#bdb5a3'},
}


def rgb(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def hexa(c):
    return '#%02x%02x%02x' % tuple(max(0, min(255, round(v * 255))) for v in c)


def mix(a, b, t):
    """t of a over b."""
    a, b = rgb(a), rgb(b)
    return hexa(tuple(a[i] * t + b[i] * (1 - t) for i in range(3)))


def hls(h, turn=0, light=None, sat=None):
    hh, ll, ss = colorsys.rgb_to_hls(*rgb(h))
    return hexa(colorsys.hls_to_rgb((hh + turn / 360) % 1, ll if light is None else light, ss if sat is None else sat))


def lum(h):
    lin = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb(h)]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast(a, b):
    x, y = sorted([lum(a), lum(b)])
    return (y + 0.05) / (x + 0.05)


def until(colour, towards, grounds, need=4.5):
    """Move colour towards another until it passes on every ground."""
    for i in range(0, 101, 2):
        c = mix(towards, colour, i / 100)
        if all(contrast(c, g) >= need for g in grounds):
            return c
    raise ValueError('no readable step from %s to %s' % (colour, towards))


def deepest(base, turn, text, cap=1.0):
    """The lightest saturated dark of a hue that keeps text at 5:1."""
    best = None
    for i in range(10, 31):
        c = hls(base, turn=turn, light=i / 100, sat=0.62)
        if contrast(text, c) >= 5:
            best = c
    return hls(best, light=colorsys.rgb_to_hls(*rgb(best))[1] * cap)


def derive(base, turn):
    out = {}
    for theme, n in NEUTRAL.items():
        t = {}
        if theme == 'light':
            t['accent'] = base
            t['on-accent'] = '#ffffff'
            t['accent-tint'] = hls(base, light=0.955, sat=0.72)
            t['accent-stock'] = hls(base, light=0.875, sat=0.74)
            t['accent-stock-2'] = hls(base, turn=turn, light=0.875, sat=0.74)
            grounds = [n['paper'], n['paper-2'], n['card'], t['accent-tint'], t['accent-stock'], t['accent-stock-2']]
            t['accent-ink'] = until(base, '#000000', grounds)
        else:
            t['accent-tint'] = mix(base, n['paper'], 0.2)
            # A dyed stock: as light as the secondary text allows, per hue.
            t['accent-stock'] = deepest(base, 0, n['ink-2'])
            t['accent-stock-2'] = deepest(base, turn, n['ink-2'], cap=0.8)
            grounds = [n['paper'], n['paper-2'], n['card'], t['accent-tint'], t['accent-stock'], t['accent-stock-2']]
            t['accent'] = until(hls(base, light=0.72, sat=0.78), '#ffffff', grounds)
            t['on-accent'] = '#14120e'
            t['accent-ink'] = t['accent']
        # What must hold, whatever the hue.
        assert contrast(t['on-accent'], t['accent']) >= 4.5, (theme, base, 'on-accent')
        for g in ('accent-tint', 'accent-stock', 'accent-stock-2'):
            for fg in (n['ink'], n['ink-2'], t['accent-ink']):
                assert contrast(fg, t[g]) >= 4.5, (theme, base, g, fg, contrast(fg, t[g]))
        for g in (n['paper'], n['paper-2'], n['card']):
            assert contrast(t['accent-ink'], g) >= 4.5, (theme, base, g)
            assert contrast(t['accent'], g) >= 3, (theme, base, g, 'fill as a UI shape')
        out[theme] = t
    return out


ORDER = ['accent', 'on-accent', 'accent-ink', 'accent-tint', 'accent-stock', 'accent-stock-2']


def block():
    lines = [BEGIN]
    for theme in ('light', 'dark'):
        pad = '' if theme == 'light' else '  '
        if theme == 'dark':
            lines.append('@media (prefers-color-scheme: dark) {')
        for name, (base, turn) in ACCENTS.items():
            t = derive(base, turn)[theme]
            sel = '[data-accent="%s"]' % name
            decl = ' '.join('--%s: %s;' % (k, t[k]) for k in ORDER)
            lines.append('%s%s { %s }' % (pad, sel, decl))
        if theme == 'dark':
            lines.append('}')
    lines.append(END)
    return '\n'.join(lines)


def table():
    rows = ['| Product | `data-accent` | Scheme | ' + ' | '.join('`--%s`' % k for k in ORDER) + ' |',
            '|---|---|---|' + '---|' * len(ORDER)]
    for name, (base, turn) in ACCENTS.items():
        d = derive(base, turn)
        for theme in ('light', 'dark'):
            rows.append('| %s | `%s` | %s | %s |' % (name, name, theme, ' | '.join('`%s`' % d[theme][k] for k in ORDER)))
    return '\n'.join(rows)


def main():
    if '--table' in sys.argv:
        print(table())
        return 0
    with open(TOKENS, encoding='utf-8') as fh:
        css = fh.read()
    new = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda m: block(), css, flags=re.S)
    # The family's own accent also sits in the two :root blocks (the docs'
    # explicit light/dark switch is built from them): first light, then dark.
    family = derive(*ACCENTS['lockfamily'])
    lines = iter([' '.join('--%s: %s;' % (k, family[t][k]) for k in ORDER) for t in ('light', 'dark')])
    new = re.sub(r'(?m)^( +)--accent: .*$', lambda m: m.group(1) + next(lines), new, count=2)
    if '--check' in sys.argv:
        if new != css or BEGIN not in css:
            print('assets/tokens.css: accents are stale, run python3 site-kit/tools/accents.py')
            return 1
        print('accents up to date')
        return 0
    with open(TOKENS, 'w', encoding='utf-8') as fh:
        fh.write(new)
    return 0


if __name__ == '__main__':
    sys.exit(main())
